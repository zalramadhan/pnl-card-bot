import { describe, expect, it } from 'vitest';
import { buildCardView } from '../src/card/card.js';
import { CARD_WIDTH, CONTENT_WIDTH, cardHeight, heroFontSize, renderCardPng } from '../src/card/render.js';
import { sampleSnapshot } from '../src/sample.js';

const PNG_MAGIC = Buffer.from([0x89, 0x50, 0x4e, 0x47]);

function pngSize(png: Buffer): { width: number; height: number } {
  return { width: png.readUInt32BE(16), height: png.readUInt32BE(20) };
}

describe('renderCardPng', () => {
  it('renders a 1080px wide PNG at the computed card height', async () => {
    const snapshot = sampleSnapshot();
    const png = await renderCardPng(snapshot, { timeZone: 'Asia/Jakarta' });
    expect(png.subarray(0, 4).equals(PNG_MAGIC)).toBe(true);

    const view = buildCardView(snapshot, 'Asia/Jakarta');
    const { width, height } = pngSize(png);
    expect(width).toBe(CARD_WIDTH);
    expect(height).toBe(cardHeight(view));
    expect(height).toBeGreaterThan(900);
    expect(height).toBeLessThan(1350);
  });

  it('is deterministic, so a stored card can be regenerated byte for byte', async () => {
    const snapshot = sampleSnapshot();
    const first = await renderCardPng(snapshot);
    const second = await renderCardPng(snapshot);
    expect(first.equals(second)).toBe(true);
  });

  it('keeps profit and loss layouts identical', async () => {
    const profit = await renderCardPng(sampleSnapshot());
    const loss = await renderCardPng(sampleSnapshot({ initialUsd: 150, receivedUsd: 141.6 }));
    expect(pngSize(profit)).toEqual(pngSize(loss));
  });

  it('renders an open position with the unrealized label and no Exit MCAP', async () => {
    const snapshot = sampleSnapshot({ status: 'open', exitMcapUsd: null });
    const png = await renderCardPng(snapshot);
    const view = buildCardView(snapshot, 'Asia/Jakarta');
    expect(view.tradeRows).toHaveLength(3);
    expect(pngSize(png).height).toBe(cardHeight(view));
  });

  it('shrinks the hero only when the amount would overflow', () => {
    expect(heroFontSize('+Rp 205.000')).toBe(124);
    const long = heroFontSize('+Rp 123.456.789');
    expect(long).toBeLessThan(124);
    expect(long * 0.55 * '+Rp 123.456.789'.length).toBeLessThanOrEqual(CONTENT_WIDTH);
  });
});
